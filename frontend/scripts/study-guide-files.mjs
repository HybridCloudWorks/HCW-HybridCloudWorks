/**
 * How the study-guide outlines are laid out on disk (#500), kept apart from
 * update-study-guides.mjs so that it imports nothing from functions/ — the
 * one-off migration, the tests and the updater all write through this, and
 * only the updater needs the parser and cheerio.
 *
 * ONE MODULE PER GUIDE, PLUS AN INDEX. Until #500 every outline lived in one
 * 491 kB module that the Azure certification detail page imported, so each
 * detail page shipped all 56 outlines (74 kB gzipped) to render one — and
 * that one was already in its prerendered HTML. Now:
 *
 *   src/data/azure/study-guides/index.js   DATA_AS_OF, DATA_SOURCE, GUIDE_KEYS
 *                                          and guideKeyFor. Small, synchronous,
 *                                          safe to import anywhere.
 *   src/data/azure/study-guides/az-104.js  `export default` one outline.
 *
 * The page imports the index and loads its one guide through
 * `import.meta.glob` (src/lib/studyGuideOutline.js), so Vite emits each guide
 * as its own chunk.
 *
 * THE DATE LIVES ONLY IN THE INDEX. A guide module carries no date, so it is
 * rewritten byte-for-byte identically when Learn has not changed that guide,
 * and the weekly refresh pull request shows exactly the guides that moved
 * rather than 56 files whose only change is a stamp.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import prettier from 'prettier';

/** Guide keys are URL tails such as `az-104`; anything else is not a guide file. */
export const GUIDE_KEY = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export const INDEX_FILE = 'index.js';

export function renderGuideFile(key, outline) {
  return `// Microsoft Learn study-guide outline for ${outline.examCode} (${key}), shown on its
// Azure certification detail page (#498, #500). Generated by
// scripts/update-study-guides.mjs; do not edit by hand. The date these outlines
// were read is DATA_AS_OF in ./index.js — deliberately not repeated here, so this
// file only changes when the guide does.
//
// Each area's \`anchor\` is the heading id read off the Learn page, so
// \`\${sourceUrl}#\${anchor}\` lands on that area; it is null where the page carried
// none. Objectives are Microsoft's wording, verbatim.

export default ${JSON.stringify(outline, null, 2)};
`;
}

export function renderIndexFile({ keys, today }) {
  const sorted = [...keys].sort();
  return `// Microsoft Learn study-guide outlines for the Azure certification detail pages (#498).
// Generated by scripts/update-study-guides.mjs from each certification's studyGuideUrl in
// certifications.js, using the same parser Listen & Learn uses
// (functions/src/lib/listen-and-learn/studyguide.js). Do not edit by hand: re-run the script.
// Last manual sync: ${today}
//
// ONE MODULE PER GUIDE (#500): each outline is ./<key>.js, loaded on its own by the
// detail page through src/lib/studyGuideOutline.js. This index is what may be imported
// synchronously — it holds no outline, so importing it costs a few hundred bytes.

/**
 * The day these outlines were last read from Microsoft Learn. Rendered by the
 * detail page beside the outline, and checked by study-guides.test.js.
 */
export const DATA_AS_OF = '${today}';

/** What a reader can check any outline against. */
export const DATA_SOURCE = {
  label: 'Microsoft Learn study guides',
  url: 'https://learn.microsoft.com/en-us/credentials/certifications/resources/study-guides/',
};

/**
 * Every guide with a module beside this file, keyed by the study-guide URL's
 * last path segment (\`az-104\`), which is unique per guide where an exam code is
 * not: the catalogue's applied-skills entries share site-assigned codes.
 *
 * Known synchronously so a page can decide whether an outline EXISTS without
 * loading it — the detail page renders no outline section at all for an exam
 * that has none, on the server and on the client alike.
 */
export const GUIDE_KEYS = Object.freeze(${JSON.stringify(sorted)});

export function guideKeyFor(studyGuideUrl) {
  const tail = String(studyGuideUrl || '')
    .split('?')[0]
    .replace(/\\/+$/, '')
    .split('/')
    .pop();
  return tail ? tail.toLowerCase() : null;
}

/** The guide key for a certification when an outline was parsed for it, else null. */
export function outlineKeyFor(studyGuideUrl) {
  const key = guideKeyFor(studyGuideUrl);
  return key && GUIDE_KEYS.includes(key) ? key : null;
}
`;
}

/**
 * Prettier with frontend/.prettierrc.json, resolved from THIS file rather than
 * from the output path, so the result is the same wherever it is written — the
 * repository's format:check covers src/, and a test writing to a temp
 * directory must get the same bytes the updater commits.
 */
async function format(source, filepath) {
  const config = await prettier.resolveConfig(fileURLToPath(import.meta.url));
  // Spreading null would not throw, but it would format with Prettier's
  // defaults, not the frontend's config, and the weekly refresh PR would then
  // fail format:check for a reason nowhere in its log. Fail here instead.
  if (!config) {
    throw new Error(
      'No Prettier config found for frontend/scripts; refusing to write study-guide modules with Prettier defaults'
    );
  }
  return prettier.format(source, { ...config, filepath });
}

/**
 * Write every outline and the index into `dir`, and delete any guide module
 * whose key is no longer in `outlines` — an exam that left the catalogue must
 * not leave an orphan chunk behind (study-guides.test.js asserts none exists).
 *
 * @returns {Promise<{written: string[], removed: string[]}>} file names
 */
export async function writeStudyGuides({ dir, outlines, today }) {
  const keys = Object.keys(outlines).sort();
  const bad = keys.filter((key) => !GUIDE_KEY.test(key) || `${key}.js` === INDEX_FILE);
  if (bad.length > 0) {
    throw new Error(`Refusing to write study guides with unusable keys: ${bad.join(', ')}`);
  }

  await fs.mkdir(dir, { recursive: true });
  const written = [];
  for (const key of keys) {
    const file = path.join(dir, `${key}.js`);
    await fs.writeFile(file, await format(renderGuideFile(key, outlines[key]), file));
    written.push(`${key}.js`);
  }
  const indexPath = path.join(dir, INDEX_FILE);
  await fs.writeFile(indexPath, await format(renderIndexFile({ keys, today }), indexPath));
  written.push(INDEX_FILE);

  const keep = new Set(written);
  const removed = [];
  for (const name of await fs.readdir(dir)) {
    if (name.endsWith('.js') && !keep.has(name)) {
      await fs.rm(path.join(dir, name));
      removed.push(name);
    }
  }
  return { written, removed };
}

/** Every stored outline in `dir`, keyed by guide; `{}` when the directory is absent. */
export async function readStudyGuides(dir, importModule = (href) => import(href)) {
  let names;
  try {
    names = await fs.readdir(dir);
  } catch {
    return {};
  }
  const outlines = {};
  for (const name of names.sort()) {
    const key = name.replace(/\.js$/, '');
    if (name === INDEX_FILE || !name.endsWith('.js') || !GUIDE_KEY.test(key)) continue;
    const mod = await importModule(`${pathToFileURL(path.join(dir, name)).href}?t=${Date.now()}`);
    if (mod?.default) outlines[key] = mod.default;
  }
  return outlines;
}
